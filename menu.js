// Given any Date, returns "week1" or "week2" based on the 2-week rotation.
function getActiveMenuWeek(date = new Date()) {
  const ref = new Date(MESS_META.weekReferenceDate + "T00:00:00");
  const msPerDay = 86400000;
  const daysSince = Math.floor((date - ref) / msPerDay);
  const weekIndex = Math.floor(daysSince / 7);
  // Normalize negative modulo (in case date is before reference)
  const parity = ((weekIndex % 2) + 2) % 2;
  return parity === 0 ? "week1" : "week2";
}

